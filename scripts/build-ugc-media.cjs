// Builds the display versions of the sample UGC journeys (photo-library/ugc/<poi>-<scene>/original.jpg)
// and writes content/ugc-media.js. Originals stay untouched; immersive-blur/photo.jpg is the copy the web and
// Android builds ship in place of original.jpg (see mobile/scripts/build.cjs). Re-run after changing a UGC photo.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
let sharp;
try { sharp = require('sharp'); } catch { sharp = require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp'); }
const root = path.resolve(__dirname, '..');
const library = path.join(root, 'photo-library', 'ugc');
const rel = file => path.relative(root, file).replaceAll('\\', '/');
const sources = JSON.parse(fs.readFileSync(path.join(library, 'sources.json'), 'utf8'));

(async () => {
  const media = {};
  for (const name of fs.readdirSync(library).sort()) {
    const dir = path.join(library, name), input = path.join(dir, 'original.jpg');
    if (!fs.existsSync(input)) continue;
    const id = `ugc-${name}`, meta = await sharp(input).metadata();
    if (meta.format !== 'jpeg' || (meta.orientation && meta.orientation !== 1)) throw Error(`${name}: expected an upright JPEG original`);
    const size = {width: meta.width, height: meta.height};
    const sha = crypto.createHash('sha256').update(fs.readFileSync(input)).digest('hex');
    const source = sources.find(item => item.dir === name) || {};
    fs.mkdirSync(path.join(dir, 'immersive-blur'), {recursive: true});
    fs.copyFileSync(input, path.join(dir, 'immersive-blur', 'photo.jpg'));
    const photo = {
      id, src: rel(input), ...size, sourceSha256: sha,
      original: {src: rel(input), ...size, bytes: fs.statSync(input).size, untouched: true},
      credit: source.artist ? `${source.artist} / Wikimedia Commons` : 'Wikimedia Commons',
      license: source.license || '', licenseUrl: source.licenseUrl || '', source: source.page || ''
    };
    for (const [variant, width, quality] of [['thumb', 480, 76], ['screen', 1080, 84], ['detail', 1600, 86]]) {
      const output = path.join(dir, `${variant}.webp`);
      const info = await sharp(input).resize({width, withoutEnlargement: true}).webp({quality, effort: 5}).toFile(output);
      photo[variant] = {src: rel(output), width: info.width, height: info.height, bytes: info.size};
    }
    fs.writeFileSync(path.join(dir, 'photo.json'), JSON.stringify({city: 'ugc', dir: name, ...photo}, null, 2) + '\n');
    media[id] = photo;
    console.log(id, `${size.width}×${size.height}`);
  }
  fs.writeFileSync(path.join(root, 'content', 'ugc-media.js'), '/* Generated by scripts/build-ugc-media.cjs */\nwindow.UGC_MEDIA = ' + JSON.stringify(media, null, 2) + ';\n');
})().catch(error => { console.error(error); process.exitCode = 1; });
