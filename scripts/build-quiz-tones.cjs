/* Run with Node and sharp installed. Small RGB maps keep automatic text contrast
   working when index.html is opened directly via file:// as well as over HTTP. */
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const sharp=require('sharp');
const root=path.resolve(__dirname,'..');
const context=vm.createContext({window:{}});
const files=['data.js','media-manifest.js',...['shenzhen','suzhou','guilin','hongkong','beijing','shanghai','zhangjiajie'].map(id=>`content/${id}.js`),'catalog.js'];
for(const file of files)vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),context);
(async()=>{
  const tones={};
  for(const city of context.window.TRIPWONDER_CATALOG.cities)for(const scene of city.scenes){
    const source=context.window.MEDIA_ASSETS[scene.id]?.screen||scene.photo;
    const {data,info}=await sharp(path.join(root,source.src.split('?')[0])).rotate().resize({width:64,height:64,fit:'inside'}).removeAlpha().toColourspace('srgb').raw().toBuffer({resolveWithObject:true});
    tones[scene.id]={width:info.width,height:info.height,rgb:data.toString('base64')};
  }
  fs.writeFileSync(path.join(root,'quiz-scene-tones.js'),'/* Generated by scripts/build-quiz-tones.cjs from local scene photographs. */\nwindow.QUIZ_SCENE_TONES='+JSON.stringify(tones)+';\n');
  console.log(`Generated contrast maps for ${Object.keys(tones).length} scenes.`);
})().catch(error=>{console.error(error);process.exitCode=1;});
