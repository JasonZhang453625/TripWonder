#!/usr/bin/env python3
"""Validate landscape sources and generate a registry; never modify original images."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import quote
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def inspect_image(relative):
    path = (ROOT / relative).resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError('图片必须存放在仓库内：' + relative)
    with Image.open(path) as image:
        if image.format not in ('JPEG', 'PNG', 'WEBP'):
            raise ValueError('请使用 JPEG、PNG 或 WebP：' + relative)
        width, height = image.size
        orientation = image.getexif().get(274, 1)
        if orientation in (5, 6, 7, 8):
            width, height = height, width
        image.verify()
    if width <= height:
        raise ValueError('只接受横屏图（按 EXIF 方向）：' + relative)
    return {'width': width, 'height': height, 'src': '../../' + quote(path.relative_to(ROOT).as_posix(), safe='/'),
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}


def build(entries):
    if not entries:
        raise ValueError('至少配置一张图片')
    scenes, ids = [], set()
    for entry in entries:
        scene_id = entry['id']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', scene_id) or scene_id in ids:
            raise ValueError('场景 ID 无效或重复：' + scene_id)
        ids.add(scene_id)
        for key in ('credit', 'source', 'license'):
            if not entry.get(key, '').strip():
                raise ValueError(f'{scene_id} 缺少 {key}')
        image = inspect_image(entry['image'])
        fallback = inspect_image(entry.get('fallback', entry['image']))
        if abs(image['width']/image['height'] - fallback['width']/fallback['height']) > .01:
            raise ValueError('回退图必须保持原图比例：' + scene_id)
        scenes.append({key: entry[key] for key in ('id', 'name', 'credit', 'source', 'license', 'licenseUrl') if key in entry} |
                      {'image': image, 'fallback': fallback})
    return scenes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=HERE / 'sphere-inputs.json')
    parser.add_argument('--output', type=Path, default=HERE / 'scenes.js')
    parser.add_argument('--check', action='store_true', help='检查配置与生成文件一致，不写文件')
    args = parser.parse_args()
    scenes = build(json.loads(args.config.read_text(encoding='utf-8')))
    content = '// Generated by workflow.py; edit sphere-inputs.json instead.\nwindow.SPHERE_SCENES = ' + json.dumps(scenes, ensure_ascii=False, indent=2) + ';\n'
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding='utf-8') != content:
            raise ValueError('生成配置已过期，请重新运行 workflow.py')
    else:
        args.output.write_text(content, encoding='utf-8')
    for scene in scenes:
        image = scene['image']
        print(f"{scene['id']}: {image['width']} × {image['height']} | ?scene={scene['id']}")


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        raise SystemExit(str(error))
